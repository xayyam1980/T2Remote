package app.t2remote.hid

/**
 * Composite HID report descriptor: keyboard (ID 1), mouse (ID 2), consumer control (ID 3).
 * Android TV accepts this as a standard Bluetooth keyboard + mouse — no app needed on the projector.
 */
object HidDescriptor {
    const val ID_KEYBOARD = 1
    const val ID_MOUSE = 2
    const val ID_CONSUMER = 3

    const val SIZE_KEYBOARD = 8   // modifiers, reserved, 6 keys
    const val SIZE_MOUSE = 4      // buttons, x, y, wheel
    const val SIZE_CONSUMER = 2   // 16-bit usage

    fun sizeOf(id: Int) = when (id) {
        ID_KEYBOARD -> SIZE_KEYBOARD
        ID_MOUSE -> SIZE_MOUSE
        ID_CONSUMER -> SIZE_CONSUMER
        else -> 0
    }

    private val raw = intArrayOf(
        // ---- Keyboard ----
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, ID_KEYBOARD,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02,             // modifier bits
        0x95, 0x01, 0x75, 0x08, 0x81, 0x01,             // reserved byte
        0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
        0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, // 6 key slots
        0xC0,
        // ---- Mouse ----
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, ID_MOUSE,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
        0x95, 0x03, 0x75, 0x01, 0x81, 0x02,             // 3 buttons
        0x95, 0x01, 0x75, 0x05, 0x81, 0x03,             // padding
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, // X, Y, wheel (relative)
        0xC0, 0xC0,
        // ---- Consumer control ----
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, ID_CONSUMER,
        0x15, 0x00, 0x26, 0xFF, 0x03, 0x19, 0x00, 0x2A, 0xFF, 0x03,
        0x75, 0x10, 0x95, 0x01, 0x81, 0x00,
        0xC0,
    )

    val bytes: ByteArray = ByteArray(raw.size) { raw[it].toByte() }
}

/** Consumer-page usages that Android maps to system keys (Generic.kl). */
object Consumer {
    const val POWER = 0x030
    const val MENU = 0x040
    const val NEXT = 0x0B5
    const val PREV = 0x0B6
    const val PLAY_PAUSE = 0x0CD
    const val MUTE = 0x0E2
    const val VOL_UP = 0x0E9
    const val VOL_DOWN = 0x0EA
    const val SEARCH = 0x221
    const val HOME = 0x223
    const val BACK = 0x224
}
